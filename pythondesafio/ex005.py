# Faca um programa que leia um numero inteiro e mostre na tela o seu sucessor e seu antecessor.

n = int(input('Numero: '))

suc = n + 1
ant = n - 1

print('Sucessor = {}'.format(suc))
print('Antecessor = {}'.format(ant))

